import { env } from "./config/env";
import { createApp } from "./app";
import { logger } from "./lib/logger";
import { createQueueMailer } from "./lib/queue";
import { prisma } from "./lib/prisma";
import { memoryLimiters, redisLimiters } from "./lib/rate-limit";
import { createBullReportQueue } from "./lib/report-queue";
import { safeErrorFields } from "./lib/safe-error";
import { initSentry } from "./lib/sentry";

const SHUTDOWN_TIMEOUT_MS = 10_000;

initSentry({
  service: "api",
  dsn: env.SENTRY_DSN,
  release: env.RENDER_GIT_COMMIT,
  nodeEnv: env.NODE_ENV,
});

const redisSetup =
  env.RATE_LIMIT_STORE === "redis" && env.REDIS_URL ? redisLimiters(env.REDIS_URL) : null;
redisSetup?.redis.on("error", (err) => logger.warn({ err: safeErrorFields(err) }, "redis error"));

// With Redis, email goes through the worker's queue so requests never wait on SMTP.
const queueMailer = env.REDIS_URL ? createQueueMailer(env.REDIS_URL) : null;
// Reports are generated by the worker when Redis is available, otherwise in this process.
const reportQueue = env.REDIS_URL ? createBullReportQueue(env.REDIS_URL) : null;

const app = createApp({
  ...(queueMailer && { mailer: queueMailer }),
  ...(reportQueue && { reportQueue }),
  limiterFactory: redisSetup?.factory ?? memoryLimiters,
  redis: redisSetup?.redis ?? null,
});

const server = app.listen(env.PORT, () => {
  logger.info({ port: env.PORT, env: env.NODE_ENV }, "api listening");
});

/** Stop accepting connections, finish in-flight requests, then close the pools. */
function shutdown(signal: string) {
  logger.info({ signal }, "shutting down");
  const force = setTimeout(() => {
    logger.error("forced shutdown after timeout");
    process.exit(1);
  }, SHUTDOWN_TIMEOUT_MS);
  force.unref();

  server.close(async () => {
    await prisma.$disconnect();
    await redisSetup?.redis.quit();
    await queueMailer?.close();
    await reportQueue?.close();
    process.exit(0);
  });
}

process.on("SIGTERM", () => shutdown("SIGTERM"));
process.on("SIGINT", () => shutdown("SIGINT"));
process.on("unhandledRejection", (reason) =>
  logger.error({ err: safeErrorFields(reason) }, "unhandled rejection"),
);
